import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';

let real = { status: 1 };
if (process.env.PRISMA_GENERATE_FORCE_FALLBACK !== '1') {
  real = spawnSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', ['prisma', 'generate'], {
    stdio: 'inherit',
    env: { ...process.env, PRISMA_GENERATE_SKIP_AUTOINSTALL: '1' },
  });
}

if (real.status === 0) process.exit(0);

const allowFallback = process.env.PRISMA_GENERATE_OFFLINE_FALLBACK !== '0';
if (!allowFallback) process.exit(real.status ?? 1);

console.warn('[prisma-generate] Real Prisma generation failed or fallback was forced; writing offline CI fallback client.');
console.warn('[prisma-generate] Set PRISMA_GENERATE_OFFLINE_FALLBACK=0 to require real Prisma engines.');

const schema = readFileSync('prisma/schema.prisma', 'utf8');
const enumBlocks = [...schema.matchAll(/enum\s+(\w+)\s*\{([\s\S]*?)\}/g)].map((m) => {
  const name = m[1];
  const values = m[2]
    .split(/\r?\n/)
    .map((line) => line.replace(/\/\/.*$/, '').trim())
    .filter(Boolean)
    .map((line) => line.split(/\s+/)[0])
    .filter((value) => /^[A-Za-z_]\w*$/.test(value));
  return { name, values };
});
const modelNames = [...schema.matchAll(/model\s+(\w+)\s*\{/g)].map((m) => m[1]);
const delegateNames = modelNames.map((name) => name[0].toLowerCase() + name.slice(1));

const outDirs = [
  join('node_modules', '.prisma', 'client'),
  join('node_modules', '@prisma', 'client', '.prisma', 'client'),
];
for (const outDir of outDirs) mkdirSync(outDir, { recursive: true });

const enumJs = enumBlocks
  .map(({ name, values }) => `const ${name} = Object.freeze({ ${values.map((v) => `${JSON.stringify(v)}: ${JSON.stringify(v)}`).join(', ')} });`)
  .join('\n');
const enumExports = enumBlocks.map(({ name }) => `  ${name},`).join('\n');

const js = `// Offline CI fallback generated by scripts/prisma-generate-offline.mjs.\n${enumJs}\n\nconst delegate = new Proxy({}, {\n  get(_target, prop) {\n    if (prop === 'count') return async () => 0;\n    if (prop === 'findMany') return async () => [];\n    if (prop === 'findUnique' || prop === 'findFirst') return async () => null;\n    return async () => { throw new Error('Offline Prisma fallback client cannot access a database. Run real prisma generate in deployment.'); };\n  },\n});\n\nclass PrismaClient {\n  constructor() {\n${delegateNames.map((name) => `    this.${name} = delegate;`).join('\n')}\n  }\n  async $connect() {}\n  async $disconnect() {}\n  async $queryRawUnsafe() { return []; }\n  async $transaction(arg) {\n    if (typeof arg === 'function') return arg(this);\n    if (Array.isArray(arg)) return Promise.all(arg);\n    return arg;\n  }\n}\n\nconst Prisma = { JsonNull: null, DbNull: null, AnyNull: null };\n\nmodule.exports = {\n  PrismaClient,\n  Prisma,\n${enumExports}\n};\n`;

const enumDts = enumBlocks
  .map(({ name, values }) => `export declare const ${name}: {\n${values.map((v) => `  readonly ${v}: ${JSON.stringify(v)};`).join('\n')}\n};\nexport type ${name} = (typeof ${name})[keyof typeof ${name}];`)
  .join('\n\n');
const modelDts = modelNames.map((name) => `export type ${name} = PrismaRecord;`).join('\n');
const delegateDts = delegateNames.map((name) => `  ${name}: PrismaDelegate;`).join('\n');

const dts = `// Offline CI fallback generated by scripts/prisma-generate-offline.mjs.\n${enumDts}\n\nexport type PrismaRecord = {\n  [key: string]: any;\n  id: string;\n  slug: string;\n  name: string;\n  email: string;\n  status: any;\n  roles: Array<{ role: AppRole }>;\n  user: PrismaRecord;\n  tenant: PrismaRecord;\n  lines: PrismaRecord[];\n  stops: PrismaRecord[];\n};\n${modelDts}\n\nexport interface PrismaDelegate {\n  findMany(args?: any): Promise<PrismaRecord[]>;\n  findUnique(args?: any): Promise<PrismaRecord | null>;\n  findFirst(args?: any): Promise<PrismaRecord | null>;\n  create(args?: any): Promise<PrismaRecord>;\n  createMany(args?: any): Promise<{ count: number }>;\n  update(args?: any): Promise<PrismaRecord>;\n  updateMany(args?: any): Promise<{ count: number }>;\n  upsert(args?: any): Promise<PrismaRecord>;\n  delete(args?: any): Promise<PrismaRecord>;\n  deleteMany(args?: any): Promise<{ count: number }>;\n  count(args?: any): Promise<number>;\n}\n\nexport declare namespace Prisma {\n  export type JsonValue = unknown;\n  export type InputJsonValue = unknown;\n  export const JsonNull: null;\n  export const DbNull: null;\n  export const AnyNull: null;\n}\n\nexport declare class PrismaClient {\n  constructor(...args: any[]);\n${delegateDts}\n  $connect(): Promise<void>;\n  $disconnect(): Promise<void>;\n  $queryRawUnsafe(query: string, ...values: unknown[]): Promise<unknown[]>;\n  $transaction<T>(arg: Promise<T>[]): Promise<T[]>;\n  $transaction<T>(arg: (tx: this) => Promise<T>): Promise<T>;\n}\n`;

for (const outDir of outDirs) {
  writeFileSync(join(outDir, 'default.js'), js);
  writeFileSync(join(outDir, 'default.d.ts'), dts);
  writeFileSync(join(outDir, 'index.js'), js);
  writeFileSync(join(outDir, 'index.d.ts'), dts);
  writeFileSync(join(outDir, 'package.json'), JSON.stringify({ name: '.prisma/client', main: 'default.js', types: 'default.d.ts' }, null, 2) + '\n');
}
console.log('[prisma-generate] Offline fallback client generated.');
